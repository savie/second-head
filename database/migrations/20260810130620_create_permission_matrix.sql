create table public.permission_matrix (
  permission_rule_id bigint generated always as identity primary key,
  actor text not null,
  authority_domain text not null,
  action text not null,
  target_domain text not null,
  target_sh text not null,
  scope_conditions text[] not null default '{}'::text[],
  decision text not null,
  created_at timestamptz not null default now(),
  constraint permission_matrix_actor_chk check (actor in ('CREATOR','SH-000','ACCOUNT_OWNER','ORDINARY_SH','SYSTEM_RUNTIME')),
  constraint permission_matrix_authority_chk check (authority_domain in ('GOVERNANCE','TECHNICAL','RUNTIME','OWNERSHIP','PRIVATE_DATA')),
  constraint permission_matrix_action_chk check (action in ('READ','WRITE','COPY_EXPORT','GOVERN','EVOLVE','EXECUTE')),
  constraint permission_matrix_target_chk check (target_domain in ('SYSTEM_CORE','SYSTEM_GOVERNANCE','GENERAL_KNOWLEDGE','SYSTEM_KNOWLEDGE','PRIVATE_MEMORY','PRIVATE_CONVERSATION','PRIVATE_CONTEXT','SH_IDENTITY','ACCOUNT')),
  constraint permission_matrix_target_sh_chk check (target_sh in ('SELF','OTHER','SYSTEM','NOT_APPLICABLE')),
  constraint permission_matrix_decision_chk check (decision in ('ALLOW','DENY','ESCALATE')),
  constraint permission_matrix_rule_uniq unique (actor, authority_domain, action, target_domain, target_sh, scope_conditions, decision)
);

comment on table public.permission_matrix is 'Phase 2 governance permission matrix. Static authorization rules; default decision remains DENY when no valid allow rule matches.';

